# compose.sh — emit a docker compose file for the selected expansions.
# shellcheck shell=bash

# Bind the stable disk mount, not servers/<short> under a /run/media path.
# udisks renames that path (NVME, NVME1, …) and Docker then keeps the empty
# directory it created while the disk was absent.
compose_volume_bind() {
  local mount="$1" ro="${2:-false}"
  cat <<EOF
    volumes:
      - type: bind
        source: ${mount}
        target: ${mount}
        read_only: ${ro}
        bind:
          propagation: rslave
          create_host_path: false
EOF
}

compose_emit() {
  local out="$1"
  shift
  local shorts=("$@")
  local short bind_addr auth_pub world_pub rest_pub
  local mount tree realm_root public_host world_pub_port
  local haproxy_ports="" octet auth_fe world_fe rest_fe port

  if [[ -z "${WOW_VOLUME_MOUNT:-}" && -f /etc/wow/volume.env ]]; then
    # shellcheck disable=SC1091
    source /etc/wow/volume.env
  fi
  mount="${WOW_VOLUME_MOUNT:-/mnt/wow-nvme}"
  tree="${WOW_TREE:-${mount}/WoW}"

  mkdir -p "$(dirname "$out")"
  {
    cat <<'HDR'
# Generated by launch-servers.sh — do not edit by hand.
name: wow

networks:
  wow:
    name: wow-net

volumes:
  wow-mariadb:

services:
  db:
    image: mariadb:11.4
    container_name: wow-db
    restart: unless-stopped
    command:
      - --character-set-server=utf8mb4
      - --collation-server=utf8mb4_unicode_ci
      - --max-allowed-packet=1G
      - --max-connections=1000
      - --innodb-buffer-pool-size=4G
      - --innodb-log-file-size=256M
      - --innodb-flush-log-at-trx-commit=2
      - --innodb-flush-method=O_DIRECT
      - --sql-mode=NO_ENGINE_SUBSTITUTION
      - --skip-name-resolve
    environment:
      MYSQL_ROOT_PASSWORD: ${MYSQL_ROOT_PASSWORD:-wow}
      MYSQL_USER: ${MYSQL_USER:-wow}
      MYSQL_PASSWORD: ${MYSQL_PASSWORD:-wow}
    ports:
      - "${MYSQL_PUBLISH_PORT:-13306}:3306"
    volumes:
      - wow-mariadb:/var/lib/mysql
    healthcheck:
      test: ["CMD", "healthcheck.sh", "--connect", "--innodb_initialized"]
      interval: 5s
      timeout: 5s
      retries: 60
      start_period: 20s
    networks: [wow]
HDR

    for short in "${shorts[@]}"; do
      catalog_load "$short" || continue
      catalog_host_ports "$short"
      bind_addr="${HOST_BIND}"
      auth_pub="${HOST_AUTH}"
      world_pub="${HOST_WORLD}"
      rest_pub="${HOST_REST}"
      realm_root="${tree}/servers/${short}"
      publish_ip="${CATALOG_LOOPBACK}"
      if [[ "$(access_mode)" == "public" ]]; then
        publish_ip="$(catalog_publish_ip "$short")"
      fi
      if [[ "${BIND_MODE:-ports}" == "haproxy" ]]; then
        public_host="$(catalog_hostname "$short")"
        world_pub_port="${CATALOG_WORLD_PORT}"
      elif [[ "${BIND_MODE:-ports}" == "loopback" ]]; then
        public_host="${CATALOG_LOOPBACK}"
        world_pub_port="${world_pub}"
      else
        public_host="${REALM_ADDRESS:-127.0.0.1}"
        world_pub_port="${world_pub}"
      fi

      cat <<EOF

  ${short}-init:
    image: wow-run-${short}:latest
    container_name: wow-${short}-init
    profiles: ["${short}"]
    restart: "no"
    depends_on:
      db:
        condition: service_healthy
    environment:
      WOW_SHORT: ${short}
      WOW_KIND: ${CATALOG_KIND}
      WOW_DB_KIND: ${CATALOG_DB_KIND}
      WOW_HOTFIX: ${CATALOG_HOTFIX}
      WOW_ROOT: ${realm_root}
      WOW_TREE: ${tree}
      WOW_VOLUME_MOUNT: ${mount}
      MYSQL_HOST: db
      MYSQL_PORT: "3306"
      MYSQL_USER: \${MYSQL_USER:-wow}
      MYSQL_PASSWORD: \${MYSQL_PASSWORD:-wow}
      MYSQL_ROOT_USER: root
      MYSQL_ROOT_PASSWORD: \${MYSQL_ROOT_PASSWORD:-wow}
EOF
      compose_volume_bind "$mount" true
      cat <<EOF
    entrypoint: ["/bin/bash", "/opt/runtime/init-db.sh"]
    networks: [wow]

  ${short}:
    image: wow-run-${short}:latest
    container_name: wow-${short}
    profiles: ["${short}"]
    restart: unless-stopped
    stop_grace_period: 30s
    depends_on:
      ${short}-init:
        condition: service_completed_successfully
    environment:
      WOW_SHORT: ${short}
      WOW_KIND: ${CATALOG_KIND}
      WOW_DB_KIND: ${CATALOG_DB_KIND}
      WOW_PROTO: ${CATALOG_PROTO}
      WOW_AUTH_BIN: ${CATALOG_AUTH_BIN}
      WOW_WORLD_BIN: ${CATALOG_WORLD_BIN}
      WOW_AUTH_PORT: "${CATALOG_AUTH_PORT}"
      WOW_WORLD_PORT: "${CATALOG_WORLD_PORT}"
      WOW_REST_PORT: "${CATALOG_REST_PORT}"
      WOW_HOTFIX: ${CATALOG_HOTFIX}
      WOW_EXPANSION: "${CATALOG_EXPANSION}"
      WOW_REALM_NAME: "${CATALOG_REALM_NAME}"
      WOW_PUBLIC_HOST: ${public_host}
      WOW_PUBLIC_WORLD_PORT: "${world_pub_port}"
      WOW_ROOT: ${realm_root}
      WOW_TREE: ${tree}
      WOW_VOLUME_MOUNT: ${mount}
      MYSQL_HOST: db
      MYSQL_PORT: "3306"
      MYSQL_USER: \${MYSQL_USER:-wow}
      MYSQL_PASSWORD: \${MYSQL_PASSWORD:-wow}
      ACCOUNT_NAME: \${ACCOUNT_NAME:-admin}
      ACCOUNT_PASSWORD: \${ACCOUNT_PASSWORD:-admin}
      FORWARD_ADDRESS_OVERRIDE: ${public_host}
EOF
      compose_volume_bind "$mount" false
      if [[ "${BIND_MODE:-ports}" != "haproxy" ]]; then
        cat <<EOF
    ports:
      - "${bind_addr}:${auth_pub}:${CATALOG_AUTH_PORT}"
      - "${bind_addr}:${world_pub}:${CATALOG_WORLD_PORT}"
      - "${bind_addr}:${HOST_WEB}:8090"
EOF
        if [[ "${CATALOG_REST_PORT}" != "0" ]]; then
          printf '      - "%s:%s:%s"\n' "$bind_addr" "$rest_pub" "$CATALOG_REST_PORT"
        fi
        if [[ "$short" == "alpha" ]]; then
          cat <<EOF
      - "${bind_addr}:9081:9081"
      - "${bind_addr}:9090:9090"
      - "${bind_addr}:9100:9100"
EOF
        fi
      else
        cat <<EOF
    ports:
      - "${publish_ip}:80:8090"
EOF
        auth_fe="$(catalog_proxy_port auth "$CATALOG_LOOPBACK")"
        world_fe="$(catalog_proxy_port world "$CATALOG_LOOPBACK")"
        haproxy_ports+="      - \"${publish_ip}:${CATALOG_AUTH_PORT}:${auth_fe}\""$'\n'
        haproxy_ports+="      - \"${publish_ip}:${CATALOG_WORLD_PORT}:${world_fe}\""$'\n'
        if [[ "${CATALOG_REST_PORT}" != "0" ]]; then
          rest_fe="$(catalog_proxy_port rest "$CATALOG_LOOPBACK")"
          haproxy_ports+="      - \"${publish_ip}:${CATALOG_REST_PORT}:${rest_fe}\""$'\n'
        fi
        if [[ "$short" == "alpha" ]]; then
          for port in 9081 9090 9100; do
            haproxy_ports+="      - \"${publish_ip}:${port}:${port}\""$'\n'
          done
        fi
      fi
      cat <<EOF
    extra_hosts:
      - "host.docker.internal:host-gateway"
    healthcheck:
      test: ["CMD", "bash", "/opt/runtime/healthcheck.sh"]
      interval: 10s
      timeout: 5s
      retries: 180
      start_period: 45m
    networks: [wow]
EOF
    done

    if [[ "${BIND_MODE:-ports}" == "haproxy" ]]; then
      cat <<'EOF'

  haproxy:
    image: haproxy:2.8
    container_name: wow-haproxy
    restart: unless-stopped
    pull_policy: missing
    volumes:
      - type: bind
        source: /etc/wow/haproxy.cfg
        target: /usr/local/etc/haproxy/haproxy.cfg
        read_only: true
        bind:
          create_host_path: false
    ports:
EOF
      printf '%s' "$haproxy_ports"
      cat <<'EOF'
    networks: [wow]
EOF
    fi
  } >"$out"
}
